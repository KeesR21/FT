/** Fisher–Yates shuffle (new array). */
export function shuffleEliteTrainingQuotes(
  quotes: EliteTrainingQuote[] = ELITE_TRAINING_QUOTES
): EliteTrainingQuote[] {
  const copy = [...quotes];
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [copy[i], copy[j]] = [copy[j]!, copy[i]!];
  }
  return copy;
}
